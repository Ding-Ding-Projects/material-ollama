/** Every glyph name available in the sprite. Passing anything else to <Icon> is a compile error. */
export type SymbolName = (typeof ICON_NAMES)[number]

/**
 * Icon sizes used across the design: the touch/dense chip sizes (14-19px),
 * the two common control sizes (20/22px). Anything else should go through the
 * `className` escape hatch rather than growing this union without a design
 * reason.
 */
// Pixel size. Deliberately a plain number: the design uses 14-22px, but a
// fixed union forces every consumer needing 26px for a dialog glyph to either
// lie about its size or patch this file, and a px measurement is not an enum.
export type IconSize = number

export interface IconProps {
  /** Glyph name, matching a symbol id generated into src/assets/icons.svg. */
  name: SymbolName
  /** Pixel size for both width and height. Defaults to 20, the most common control size. */
  size?: IconSize
  /**
   * Use the filled (FILL 1) variant. Only a subset of icons ship a filled
   * symbol -- see FILL_ICON_NAMES in scripts/build-icon-sprite.mjs (the nav
   * rail destinations, the dim sum glyph, and the app-logo picker glyphs).
   * Requesting `fill` on a name outside that set renders nothing, the same
   * way any other missing symbol id would.
   */
  fill?: boolean
  className?: string
}

/**
 * A single Material Symbols (Outlined) glyph, rendered from the local sprite.
 *
 * `<use>` points at the Vite-resolved sprite URL plus a `#ms-<name>` fragment
 * rather than a bare `#ms-<name>` href. A bare fragment only resolves if the
 * sprite's raw markup is inlined into this document somewhere, which nothing
 * in this component's scope does; referencing the built asset URL is
 * self-contained and needs no such global wiring. WebView2 (Chromium) fully
 * supports cross-document `<use>` fragment references, so this works exactly
 * like an inline sprite would, without depending on where else in the app the
 * sprite happens to be mentioned.
 */
export function Icon({ name, size = 20, fill = false, className }: IconProps) {
  const symbolId = fill ? `ms-${name}-fill` : `ms-${name}`
  return (
    <svg
      width={size}
      height={size}
      fill="currentColor"
      aria-hidden="true"
      className={className}
    >
      <use href={`${iconsSpriteUrl}#${symbolId}`} />
    </svg>
  )
}
