// Renders a Material Symbols (Outlined) glyph from the local sprite at
// src/assets/icons.svg via <use>, instead of the ligature icon font.
//
// Why: the ligature approach (`<span class="material-symbols-outlined">
// rocket_launch</span>`) fails ugly -- a missing or misspelled glyph renders
// the literal English word as body text. A missing <use> target here instead
// renders nothing (an empty box), and the SymbolName union type below turns a
// typo into a compile error in the first place, so that failure mode should
// never reach runtime.
//
// The sprite itself, and the ICON_NAMES list between the markers below, are
// generated by scripts/build-icon-sprite.mjs -- run it after adding a new
// `<Icon name="...">` usage so both stay in sync. Everything outside the
// marked block is hand-written and untouched by that script.

